"""Builds native/src/icons_gen.inc from the web app's SVG sprite, so both apps draw the same icons.

Every shape is turned into an SVG path string; circles and rectangles become arcs, which the native
renderer reads with the same path parser as everything else.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent.parent
html = (root / "index.html").read_text(encoding="utf-8")


def num(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def circle(cx, cy, r):
    return f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0Z"


def rect(x, y, w, h, rx):
    if rx <= 0:
        return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
    iw, ih = w - 2 * rx, h - 2 * rx
    a = f"a{num(rx)} {num(rx)} 0 0 1 "
    return (f"M{num(x + rx)} {num(y)}h{num(iw)}{a}{num(rx)} {num(rx)}v{num(ih)}{a}{num(-rx)} {num(rx)}"
            f"h{num(-iw)}{a}{num(-rx)} {num(-rx)}v{num(-ih)}{a}{num(rx)} {num(-rx)}Z")


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def shapes(body):
    out = []
    for m in re.finditer(r"<(path|circle|rect)\b([^>]*)/?>", body):
        kind, rest = m.group(1), m.group(2)
        a = attrs(rest)
        filled = a.get("fill") == "currentColor"
        if kind == "path":
            out.append((a["d"], filled))
        elif kind == "circle":
            out.append((circle(float(a["cx"]), float(a["cy"]), float(a["r"])), filled))
        else:
            out.append((rect(float(a["x"]), float(a["y"]), float(a["width"]), float(a["height"]), float(a.get("rx", 0))), filled))
    return out


icons = []
for m in re.finditer(r'<symbol id="(i-[\w-]+)" viewBox="0 0 24 24">(.*?)</symbol>', html, re.S):
    icons.append((m.group(1), shapes(m.group(2))))

# the logo is inline in the header
lm = re.search(r'<svg class="logo"[^>]*>(.*?)</svg>', html, re.S)
icons.append(("logo", shapes(lm.group(1))))

lines = ["// Generated by native/tools/gen_icons.py from index.html. Do not edit by hand."]
for name, sh in icons:
    parts = ", ".join('{"%s", %s}' % (d, "true" if f else "false") for d, f in sh)
    lines.append('{"%s", {%s}},' % (name, parts))
out = root / "native" / "src" / "icons_gen.inc"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(icons)} icons -> {out}")
